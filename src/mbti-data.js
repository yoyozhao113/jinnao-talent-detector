/**
 * 根据答案计算 MBTI 类型
 * @param {Object} answers - { questionId: 'a'|'b' }
 * @returns {Object} { type, dimensionScores, ...typeProfile }
 */
export function calculateMBTI(answers) {
  // 统计各维度题数（动态支持不同数量的题目）
  const dimCount = { EI: 0, SN: 0, TF: 0, JP: 0 };
  MBTI_QUESTIONS.forEach(q => { dimCount[q.dim]++; });

  const dims = { EI: 0, SN: 0, TF: 0, JP: 0 };
  MBTI_QUESTIONS.forEach(q => {
    const choice = answers[q.id];
    if (!choice) return;
    if (choice === 'a') dims[q.dim]--;
    else dims[q.dim]++;
  });

  const type =
    (dims.EI <= 0 ? 'E' : 'I') +
    (dims.SN <= 0 ? 'S' : 'N') +
    (dims.TF <= 0 ? 'T' : 'F') +
    (dims.JP <= 0 ? 'J' : 'P');

  const profile = MBTI_TYPES[type];
  const toPercent = (score, dim) => Math.round(Math.abs(score) / dimCount[dim] * 100);

  // 判断倾向强度
  const getTendency = (score, dim) => {
    const p = toPercent(score, dim);
    if (p >= 80) return '非常明显';
    if (p >= 50) return '比较明显';
    return '略有倾向';
  };

  return {
    type,
    ...profile,
    dimensionScores: {
      EI: { score: dims.EI, percent: toPercent(dims.EI, 'EI'), label: dims.EI <= 0 ? 'E 外向' : 'I 内向', tendency: getTendency(dims.EI, 'EI') },
      SN: { score: dims.SN, percent: toPercent(dims.SN, 'SN'), label: dims.SN <= 0 ? 'S 感觉' : 'N 直觉', tendency: getTendency(dims.SN, 'SN') },
      TF: { score: dims.TF, percent: toPercent(dims.TF, 'TF'), label: dims.TF <= 0 ? 'T 思维' : 'F 情感', tendency: getTendency(dims.TF, 'TF') },
      JP: { score: dims.JP, percent: toPercent(dims.JP, 'JP'), label: dims.JP <= 0 ? 'J 判断' : 'P 感知', tendency: getTendency(dims.JP, 'JP') },
    },
  };
}
